def _fuzzy_in(word: str, target: str) -> bool:
    """Cheap typo tolerance: word matches if it appears with one character wrong/missing."""
    if len(word) < 4:
        return False
    for i in range(len(word)):
        if word[:i] + word[i + 1:] in target:
            return True
    for i in range(1, len(word)):
        if word[:i] in target and word[i:] in target:
            return True
    return False


